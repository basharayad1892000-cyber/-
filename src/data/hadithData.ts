// Fast lookup map of curated Hadith commentary & chapter metadata by `${bookId}:${hadithNumber}`
export const CURATED_HADITH_BY_KEY = new Map<string, HadithItem>();
HADITH_COLLECTION.forEach(item => {
  CURATED_HADITH_BY_KEY.set(`${item.bookId}:${item.hadithNumber}`, item);
});

/**
 * Derives a concise, meaningful Arabic Chapter (باب) title for a group of hadiths
 * inside an original Sub-Book (كتاب), using either curated chapter titles,
 * explicit "باب ..." headings inside the text, or the prophetic quote snippet.
 */
function deriveChapterTitleForGroup(
  bookId: HadithBookId,
  subBookTitle: string,
  chapterIdx: number,
  groupHadiths: RawElectronicHadith[],
  totalChaptersInSubBook: number
): string {
  // 1. Check if any hadith in this group has a curated chapter title
  for (const h of groupHadiths) {
    const curated = CURATED_HADITH_BY_KEY.get(`${bookId}:${h.n}`);
    if (curated && curated.chapterTitle) {
      return curated.chapterTitle;
    }
  }

  const firstHadith = groupHadiths[0];
  if (!firstHadith) return `الباب ${chapterIdx + 1} من ${subBookTitle}`;

  // 2. Check if text starts with "باب "
  const trimmed = firstHadith.t.trim();
  if (trimmed.startsWith('باب ') || trimmed.startsWith('بَابُ ') || trimmed.startsWith('بَاب ')) {
    const firstLine = trimmed.split(/[\n.،:]/)[0].trim();
    if (firstLine.length > 4 && firstLine.length <= 95) {
      return firstLine;
    }
  }

  // 3. Extract the prophetic quote after قَالَ رَسُولُ اللَّهِ / يَقُولُ / قَالَ : " ... "
  const quoteMatch =
    trimmed.match(/[«"]([^»"]{10,85})/) ||
    trimmed.match(/يَقُولُ\s*:\s*([^\n.،]{10,80})/) ||
    trimmed.match(/قَالَ\s*:\s*([^\n.،]{10,80})/);

  const rangeLabel =
    groupHadiths.length > 1
      ? ` (الأحاديث ${groupHadiths[0].n} - ${groupHadiths[groupHadiths.length - 1].n})`
      : ` (حديث ${groupHadiths[0].n})`;

  if (quoteMatch && quoteMatch[1]) {
    const cleanSnippet = quoteMatch[1].replace(/["«»]/g, '').trim();
    const words = cleanSnippet.split(/\s+/).slice(0, 8).join(' ');
    return `باب: ${words}...${rangeLabel}`;
  }

  if (totalChaptersInSubBook === 1) {
    return `باب أحاديث ${subBookTitle}${rangeLabel}`;
  }

  return `الباب (${chapterIdx + 1}) من ${subBookTitle}${rangeLabel}`;
}

/**
 * Builds the complete 3-level hierarchical tree for an Electronic Hadith Book:
 * Level 1: Collection (المصنّف الحديثي)
 * Level 2: Original Sub-Books (الكتب الأصلية داخل المصنّف مثل كتاب بدء الوحي، كتاب الإيمان...)
 * Level 3: Original / Grouped Chapters (الأبواب الأصلية داخل كل كتاب) -> Hadiths in original order
 */
export function buildElectronicBookTree(
  bookPayload: FullElectronicBookPayload
): HadithTreeCollectionNode {
  const indexMeta = ENCYCLOPEDIA_BOOKS_INDEX.find(b => b.id === bookPayload.id);

  // Group hadiths by original subBookId (`h.c`)
  const hadithsBySubBook = new Map<number, RawElectronicHadith[]>();
  for (const h of bookPayload.hadiths) {
    const cid = h.c || 1;
    let arr = hadithsBySubBook.get(cid);
    if (!arr) {
      arr = [];
      hadithsBySubBook.set(cid, arr);
    }
    arr.push(h);
  }

  const rawSubBooks =
    bookPayload.chapters && bookPayload.chapters.length > 0
      ? bookPayload.chapters
      : [
          {
            id: 1,
            number: 1,
            title: `كتاب ${bookPayload.title}`,
            count: bookPayload.hadiths.length,
          },
        ];

  const CHUNK_SIZE = 15; // Group large sub-books into navigable 15-hadith chapters (أبواب)

  const subBooks: HadithTreeSubBookNode[] = rawSubBooks
    .map((sb, idx) => {
      const sbHadiths = hadithsBySubBook.get(sb.id) || [];
      if (sbHadiths.length === 0) return null;

      const chapters: HadithTreeChapterNode[] = [];
      const totalChunks = Math.ceil(sbHadiths.length / CHUNK_SIZE);

      for (let i = 0; i < sbHadiths.length; i += CHUNK_SIZE) {
        const slice = sbHadiths.slice(i, i + CHUNK_SIZE);
        const chapterIdx = Math.floor(i / CHUNK_SIZE);
        const chapterTitle = deriveChapterTitleForGroup(
          bookPayload.id,
          sb.title,
          chapterIdx,
          slice,
          totalChunks
        );

        chapters.push({
          chapterKey: `${bookPayload.id}-sb${sb.id}-ch${chapterIdx + 1}`,
          chapterNumber: chapterIdx + 1,
          chapterTitle,
          subBookId: sb.id,
          subBookTitle: sb.title,
          hadithStart: slice[0].n,
          hadithEnd: slice[slice.length - 1].n,
          hadiths: slice,
        });
      }

      return {
        subBookId: sb.id,
        subBookNumber: sb.number || idx + 1,
        subBookTitle: sb.title,
        totalHadiths: sbHadiths.length,
        chapters,
      };
    })
    .filter((item): item is HadithTreeSubBookNode => item !== null);

  return {
    bookId: bookPayload.id,
    title: bookPayload.title,
    author: bookPayload.author,
    subtitle: indexMeta?.subtitle || '',
    badge: bookPayload.badge,
    grade: bookPayload.grade,
    totalHadiths: bookPayload.totalHadiths || bookPayload.hadiths.length,
    subBooksCount: subBooks.length,
    subBooks,
  };
}

